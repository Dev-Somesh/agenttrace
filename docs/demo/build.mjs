/**
 * Builds the published demo: stages the project, exports the console, and
 * marks the result as staged data.
 *
 *   node docs/demo/build.mjs [outdir]      # default: site/
 *
 * The banner is not decoration. This tool's whole argument is that its numbers
 * survive being checked, so a demo that reads like someone's real project would
 * undercut the thing it is demonstrating. Anyone landing on the page is told in
 * the first line that the runs are synthetic.
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(HERE, "..", "..");
const SITE = path.resolve(process.argv[2] || path.join(REPO, "site"));
const STAGE = fs.mkdtempSync(path.join(os.tmpdir(), "runlanes-demo-"));

const node = process.execPath;
const run = (args, env) =>
  execFileSync(node, args, { cwd: REPO, env: { ...process.env, ...env }, encoding: "utf8" });

const staged = JSON.parse(run([path.join(HERE, "generate.mjs"), STAGE]));
const out = path.join(STAGE, "demo.html");
run([path.join(REPO, "src", "cli.js"), "--dir", staged.cwd, "--export", out], { HOME: staged.home });

const BANNER = `
<style>
  .demo-note {
    font: 12px/1.5 ui-monospace, SFMono-Regular, Menlo, monospace;
    background: #0b0f14; color: #cbd5e1; border-bottom: 1px solid #1e293b;
    padding: 10px 16px; text-align: center;
  }
  .demo-note a { color: #3DDC97; }
  .demo-note strong { color: #f8fafc; }
</style>
<div class="demo-note">
  <strong>A demonstration.</strong> These runs are staged, not measured — generated by
  <a href="https://github.com/Dev-Somesh/runlanes/blob/main/docs/demo/generate.mjs">docs/demo/generate.mjs</a>
  so the console has something to draw. Run <strong>npx runlanes</strong> in your own project to see your own.
  &nbsp;·&nbsp; <a href="https://github.com/Dev-Somesh/runlanes">GitHub</a>
  &nbsp;·&nbsp; <a href="https://www.npmjs.com/package/runlanes">npm</a>
</div>`;

let html = fs.readFileSync(out, "utf8");
if (!html.includes("<body>")) throw new Error("export no longer has a <body> to mark");
html = html.replace("<body>", "<body>" + BANNER);

fs.rmSync(SITE, { recursive: true, force: true });
fs.mkdirSync(SITE, { recursive: true });
fs.writeFileSync(path.join(SITE, "index.html"), html);
// Pages would otherwise hand the file to Jekyll, which eats paths beginning "_".
fs.writeFileSync(path.join(SITE, ".nojekyll"), "");
fs.rmSync(STAGE, { recursive: true, force: true });

console.log(`wrote ${path.join(SITE, "index.html")} (${(html.length / 1024).toFixed(0)}KB)`);
